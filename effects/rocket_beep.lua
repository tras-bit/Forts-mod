--  ЭТО БЫЛ ГЛАВНЫЙ ИСТОЧНИК «ПИЗДЫ УШАМ». Разбор:
--
--  Сэмпл homing_beep.wav — тон ~5.5 кГц, нормализованный по пику
--  (RMS -3.7 dBFS, пик 0 dB). 5.5 кГц — область максимальной
--  чувствительности уха (резонанс слухового канала 2-5 кГц),
--  то есть САМАЯ неприятная частота из возможных.
--
--  А в script.lua этот звук вызывался КАЖДЫЕ 10 КАДРОВ
--  (beepTimer >= 10, при 60 fps это ~6 раз в секунду) и на КАЖДУЮ
--  летящую ракету. Четыре ракеты = 24 писка в секунду на полной
--  громкости, без затухания, да ещё и PlayForEnemy = true —
--  то есть слышно было и врагу.
--
--  СТАЛО:
--    * Volume = 0.10 вместо 1.0  (на 20 dB тише);
--    * FalloffStart/End — писк глохнет уже с 800 ед., полностью
--      исчезает к 4000 (это РЕАЛЬНЫЕ поля движка, см. barrel_explode);
--    * PlayForEnemy = false — враг свой писк не слышит;
--    * Priority низкий — вытесняется любым важным звуком;
--    * частоту вызова снизил в script.lua (BEEP_PERIOD = 30 кадров).
-- ============================================================
